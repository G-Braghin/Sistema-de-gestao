def montar_service(conexao):
    produtos = ProdutoRepository(conexao)
    movimentacoes = MovimentacaoRepository(conexao)
    estoque = EstoqueService(produtos, movimentacoes, conexao)
    return VendaService(
        conexao, VendaRepository(conexao), produtos,
        ClienteRepository(conexao), estoque,
    )


def test_buscar_produto_para_atualizar_retorna_dados_ou_none(banco_isolado):
    conexao = banco_isolado()
