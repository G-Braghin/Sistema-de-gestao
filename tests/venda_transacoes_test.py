@pytest.mark.parametrize('metodo, campo, valor', [
    ('atualizar_nome', 'nome', 'CANETA NOVA'),
    ('atualizar_marca', 'marca', 'MARCA NOVA'),
    ('atualizar_preco', 'preco', '3.50'),
])
def test_editar_produto_preserva_estoque_alterado_por_outra_transacao(
    banco_isolado, metodo, campo, valor
):
    primeira = banco_isolado().get_connection()
    segunda = banco_isolado()
    observador = banco_isolado().get_connection()
    observador.autocommit = True
    service = ProdutoService(ProdutoRepository(segunda), segunda)
    with primeira.cursor() as cursor:
        cursor.execute('UPDATE produtos SET quantidade_estoque = 1 WHERE id_produto = 1')

    with ThreadPoolExecutor(max_workers=1) as executor:
        tarefa = executor.submit(getattr(service, metodo), 1, valor)
        try:
            prazo = monotonic() + 10
            while True:
                with observador.cursor() as cursor:
                    cursor.execute('SELECT pg_blocking_pids(%s)',
                                   (segunda.get_connection().get_backend_pid(),))
                    bloqueadores = cursor.fetchone()[0]
                if primeira.get_backend_pid() in bloqueadores:
                    break
                if tarefa.done():
                    tarefa.result()
                    pytest.fail('A edicao deveria esperar a alteracao de estoque')
                assert monotonic() < prazo, 'A edicao nao aguardou o bloqueio'
                sleep(0.02)
        finally:
            primeira.commit()
        tarefa.result(timeout=20)

    with observador.cursor() as cursor:
        cursor.execute(sql.SQL(
            'SELECT quantidade_estoque, {} FROM produtos WHERE id_produto = 1'
        ).format(sql.Identifier(campo)))
        saldo, alterado = cursor.fetchone()
    assert saldo == 1, 'A edicao sobrescreveu o estoque com o saldo antigo'
    assert str(alterado) == valor


@pytest.mark.parametrize('falhar_na_movimentacao', [1, 2])
def test_falha_na_movimentacao_desfaz_venda_itens_e_estoque(
    banco_isolado, usuario, falhar_na_movimentacao
):
    conexao = banco_isolado()
    service = montar_service(conexao)
    repository = service.estoque_service.movimentacao_repository
    criar_original = repository.criar
    chamadas = []

    def criar_com_falha(movimentacao):
        resultado = criar_original(movimentacao)
        chamadas.append(resultado)
        if len(chamadas) == falhar_na_movimentacao:
            # Erro real do PostgreSQL depois de a movimentacao ser inserida.
            with conexao.get_connection().cursor() as cursor:
                cursor.execute('SELECT 1 / 0')
        return resultado

    with patch.object(repository, 'criar', side_effect=criar_com_falha):
        with pytest.raises(psycopg2.errors.DivisionByZero):
            service.realizar_venda(usuario, 1, [
                {'id_produto': 1, 'quantidade': 2},
                {'id_produto': 2, 'quantidade': 1},
            ])

    assert len(chamadas) == falhar_na_movimentacao
    # Uma conexao independente verifica o que realmente ficou salvo.
    with banco_isolado().get_connection().cursor() as cursor:
        cursor.execute('SELECT quantidade_estoque FROM produtos ORDER BY id_produto')
        assert cursor.fetchall() == [(5,), (5,)]
        for tabela in ['vendas', 'venda_itens', 'movimentacoes_estoque']:
            cursor.execute(sql.SQL('SELECT COUNT(*) FROM {}').format(sql.Identifier(tabela)))
            assert cursor.fetchone()[0] == 0, tabela


def test_vendas_simultaneas_nao_vendem_mais_que_o_estoque(banco_isolado, usuario):
    primeira = banco_isolado()
    segunda = banco_isolado()
    observador = banco_isolado().get_connection()
    observador.autocommit = True
    primeira_leu = Event()
    segunda_leu = Event()
    liberar_primeira = Event()

    def vender(conexao, sinal, pausar):
        service = montar_service(conexao)
        estoque = service.estoque_service
        buscar_original = estoque.produto_repository.buscar_por_id_para_atualizar
        saida_original = estoque.registrar_saida

        def buscar_e_sincronizar(id_produto):
            produto = buscar_original(id_produto)
            sinal.set()
            if pausar and not liberar_primeira.wait(10):
                raise TimeoutError('A primeira venda nao foi liberada')
            return produto

        def saida_sincronizada(*args, **kwargs):
            # Controla a leitura que antecede a baixa, sem simular o banco.
            with patch.object(estoque.produto_repository, 'buscar_por_id_para_atualizar',
                              side_effect=buscar_e_sincronizar):
                return saida_original(*args, **kwargs)

        with patch.object(estoque, 'registrar_saida', side_effect=saida_sincronizada):
            try:
                return service.realizar_venda(usuario, 1, [{'id_produto': 1, 'quantidade': 4}])
            except ValueError as erro:
                return erro

    with ThreadPoolExecutor(max_workers=2) as executor:
        tarefa1 = executor.submit(vender, primeira, primeira_leu, True)
        try:
            assert primeira_leu.wait(10), 'A primeira venda nao chegou a leitura do estoque'
            tarefa2 = executor.submit(vender, segunda, segunda_leu, False)
            prazo = monotonic() + 10
            while not segunda_leu.is_set():
                # Se o codigo usar FOR UPDATE, a segunda leitura deve esperar
                # pelo lock da primeira, e tambem podemos libera-la com seguranca.
                with observador.cursor() as cursor:
                    cursor.execute('SELECT pg_blocking_pids(%s)',
                                   (segunda.get_connection().get_backend_pid(),))
                    bloqueadores = cursor.fetchone()[0]
                if primeira.get_connection().get_backend_pid() in bloqueadores:
                    break
                if tarefa2.done():
                    tarefa2.result()  # Nao esconder erros inesperados da thread.
                    pytest.fail('A segunda venda terminou antes da leitura esperada')
                assert monotonic() < prazo, 'A segunda venda nao chegou a leitura nem aguardou lock'
                sleep(0.02)
        finally:
            liberar_primeira.set()
        resultados = [tarefa1.result(timeout=20), tarefa2.result(timeout=20)]

    with observador.cursor() as cursor:
        cursor.execute('SELECT quantidade_estoque FROM produtos WHERE id_produto = 1')
        saldo = cursor.fetchone()[0]
        cursor.execute('SELECT COUNT(*) FROM vendas')
        vendas = cursor.fetchone()[0]
        cursor.execute('SELECT COALESCE(SUM(quantidade), 0) FROM venda_itens')
        unidades = cursor.fetchone()[0]
        cursor.execute('SELECT COUNT(*), COALESCE(SUM(quantidade), 0) FROM movimentacoes_estoque')
        movimentacoes, saidas = cursor.fetchone()

    assert (vendas, unidades, saldo, movimentacoes, saidas) == (1, 4, 1, 1, 4), (
        f'Concorrencia incorreta: {vendas} vendas, {unidades} unidades vendidas, '
        f'saldo {saldo}, {movimentacoes} movimentacoes e {saidas} unidades de saida. '
        'O estoque inicial era de apenas 5 unidades.'
    )
    recusadas = [resultado for resultado in resultados if isinstance(resultado, ValueError)]
    assert len(recusadas) == 1
    assert 'Estoque' in str(recusadas[0])
